//! Vault entry domain model. All fields are owned and serde-serializable so
//! the same types cross the (future) UniFFI boundary unchanged. The list API
//! only ever hands out [`EntrySummary`]; a full [`Entry`] (with its password)
//! is disclosed one at a time through [`crate::Core::entry`], laying the
//! groundwork for the on-demand disclosure of P10/P11.

use serde::{Deserialize, Serialize};
use zeroize::Zeroize;

/// One stored credential. `password` and `notes` are sensitive: the whole
/// entry is zeroized when the core locks (see [`crate::Core::lock`]).
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize, Zeroize)]
pub struct Entry {
    /// Stable random identifier (hex), generated by the core on add.
    pub id: String,
    pub title: String,
    pub username: String,
    pub password: String,
    /// Associated URLs (login origins), used later for domain matching.
    pub urls: Vec<String>,
    pub notes: String,
    /// Unix seconds, set by the core when the entry is created.
    pub created_at: u64,
    /// Unix seconds, refreshed by the core on every update.
    pub updated_at: u64,
}

impl Entry {
    /// The non-sensitive projection shown in lists.
    pub fn summary(&self) -> EntrySummary {
        EntrySummary {
            id: self.id.clone(),
            title: self.title.clone(),
            username: self.username.clone(),
        }
    }
}

/// The list projection of an [`Entry`]: never carries the password or notes.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct EntrySummary {
    pub id: String,
    pub title: String,
    pub username: String,
}

/// The caller-supplied fields of a new entry. The core fills in `id` and the
/// timestamps, so callers cannot forge them.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct EntryDraft {
    pub title: String,
    pub username: String,
    pub password: String,
    pub urls: Vec<String>,
    pub notes: String,
}
